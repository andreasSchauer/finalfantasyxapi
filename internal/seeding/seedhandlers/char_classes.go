package seedhandlers

import (
	"context"
	"fmt"

	"github.com/andreasSchauer/finalfantasyxapi/internal/database"
	"github.com/andreasSchauer/finalfantasyxapi/internal/lookup"
	sh "github.com/andreasSchauer/finalfantasyxapi/internal/seeding/seedhelpers"
	"github.com/andreasSchauer/finalfantasyxapi/internal/seeding/seedtypes"
)

func Loop1CharacterClasses(qtx *database.Queries, ctx context.Context) error {
	classes := sh.DedupeRows(sh.RawJSON.CharacterClasses, sh.Hashes)

	params := database.CreateCharacterClassBulkParams{
		DataHash: make([]string, len(classes)),
		Name:     make([]string, len(classes)),
		Category: make([]database.CharacterClassCategory, len(classes)),
	}

	for i, c := range classes {
		params.DataHash[i] = sh.GenerateDataHash(c)
		params.Name[i] = c.Name
		params.Category[i] = database.CharacterClassCategory(c.Category)
	}

	dbRows, err := qtx.CreateCharacterClassBulk(ctx, params)
	if err != nil {
		return fmt.Errorf("couldn't create character classes: %v", err)
	}

	for i, row := range dbRows {
		classes[i].ID = row.ID
		sh.RawJSON.CharacterClasses[i].ID = row.ID
		lookup.L.CharClasses[seedtypes.Key(classes[i])] = classes[i]
		lookup.L.CharClassesID[row.ID] = classes[i]
		sh.Hashes[row.DataHash] = row.ID
	}

	return nil
}
